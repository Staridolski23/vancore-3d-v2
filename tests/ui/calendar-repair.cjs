const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path');
const {companyClock}=require('../../ops/backend/booking-policy.cjs');
exports.run=async function(page,context,outputDirectory){
 const base='http://127.0.0.1:3100',results=[];let failAvailability=true,postCount=0,created=false;
 const [year,month]=companyClock().date.split('-').map(Number),next=new Date(Date.UTC(year,month,1));
 while(next.getUTCDay()!==1)next.setUTCDate(next.getUTCDate()+1);
 const date=next.toISOString().slice(0,10);
 await context.unroute('**/*');
 await context.route('**/*',async route=>{
  const request=route.request(),url=new URL(request.url());if(url.hostname!=='127.0.0.1')return route.abort();
  if(!url.pathname.startsWith('/api/'))return route.continue();
  const reply=(data,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(data)});
  if(url.pathname==='/api/bookings'){
   if(request.method()==='GET')return failAvailability||created?reply({error:'Synthetic availability outage'},503):reply({bookings:{[date]:['09:00','09:30']}});
   postCount++;await new Promise(resolve=>setTimeout(resolve,650));
   if(postCount===1)return reply({error:'Synthetic interval conflict'},409);
   created=true;return reply({success:true,id:1},201);
  }
  if(url.pathname==='/api/content')return reply({sections:{},order:[]});
  if(url.pathname==='/api/auth/profile')return reply({error:'No synthetic user'},401);
  return reply({});
 });
 await page.setViewportSize({width:1280,height:900});
 await page.goto(base+'/login');await page.evaluate(()=>localStorage.removeItem('vancore_client_token'));
 await page.goto(base+'/book-call');
 await page.getByRole('alert').filter({hasText:'Availability could not be loaded.'}).waitFor();
 assert.ok(await page.getByRole('button',{name:/^\d{4}-\d{2}-\d{2}$/}).evaluateAll(elements=>elements.every(element=>element.disabled)));
 results.push({check:'Availability outage disables dates rather than showing a free calendar',status:'PASS'});
 failAvailability=false;await page.reload();
 await page.getByText('45 minutes · All times in Europe/Sofia',{exact:true}).waitFor();
 await page.getByRole('button',{name:'→',exact:true}).click();
 const day=page.getByRole('button',{name:date,exact:true});await day.waitFor();
 await page.waitForFunction(label=>!Array.from(document.querySelectorAll('button')).find(button=>button.getAttribute('aria-label')===label)?.disabled,date);
 await day.focus();await page.keyboard.press('Enter');
 assert.equal(await page.getByRole('button',{name:'09:00',exact:true}).isEnabled(),false);
 assert.equal(await page.getByRole('button',{name:'09:30',exact:true}).isEnabled(),false);
 await page.getByRole('button',{name:'10:00',exact:true}).click();
 results.push({check:'Keyboard date selection and interval-blocked time choices work in the labelled Sofia timezone',status:'PASS'});
 await page.getByPlaceholder('John Doe',{exact:true}).fill('Synthetic Calendar Client');
 await page.getByPlaceholder('you@company.com',{exact:true}).fill('qa@example.invalid');
 await page.getByPlaceholder("Describe the topic you'd like to discuss...",{exact:true}).fill('Synthetic booking fixture; no actual booking or email.');
 await page.getByRole('button',{name:'Request this time',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Saving...',exact:true}).isEnabled(),false);
 await page.getByText('Synthetic interval conflict',{exact:true}).waitFor();
 assert.equal(await page.getByPlaceholder('John Doe',{exact:true}).inputValue(),'Synthetic Calendar Client');assert.equal(postCount,1);
 results.push({check:'Conflict is visible, draft is preserved and submit is disabled while saving',status:'PASS'});
 await page.getByRole('button',{name:'Request this time',exact:true}).click();
 await page.getByRole('heading',{name:'Booking request received',exact:true}).waitFor();
 await page.getByRole('alert').filter({hasText:'Your request was saved, but availability could not be refreshed.'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'10:30',exact:true}).isEnabled(),false);
 await page.getByRole('button',{name:'Reload availability',exact:true}).waitFor();
 assert.equal(postCount,2);assert.equal(await page.getByText("We'll send you a confirmation email shortly.",{exact:true}).count(),0);
 results.push({check:'Saved request remains successful when refresh fails; no false confirmation-email promise',status:'PASS'});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('heading',{name:'Booking request received',exact:true}).scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
 await page.screenshot({path:path.join(outputDirectory,'VANCORE-calendar-mobile-qa.png'),scale:'css'});
 const report={date:new Date().toISOString(),environment:'localhost with intercepted synthetic APIs',realBookingsCreated:0,realEmailsSent:0,results};
 await fs.writeFile(path.join(outputDirectory,'VANCORE-calendar-ui-qa.json'),JSON.stringify(report,null,2));return report;
};
